const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

/** '2026-05' -> 'May 2026' */
export const formatMonth = (ym: string): string => {
  const [year, month] = ym.split('-');
  return `${MONTHS[Number(month) - 1]} ${year}`;
};

/** Formats a start/end pair, collapsing a shared year: 'May – Aug 2026'. */
export const formatRange = (start: string, end: string | null): string => {
  if (end === null) return `${formatMonth(start)} – Present`;
  const [startYear] = start.split('-');
  const [endYear] = end.split('-');
  if (startYear === endYear) return `${formatMonth(start).split(' ')[0]} – ${formatMonth(end)}`;
  return `${formatMonth(start)} – ${formatMonth(end)}`;
};

/** '2025-11-17' -> 'Nov 17, 2025' */
export const formatDay = (ymd: string): string => {
  const [year, month, day] = ymd.split('-');
  return `${MONTHS[Number(month) - 1]} ${Number(day)}, ${year}`;
};
